using Npgsql;
using PmsDemoReset;
using Xunit;

public class ResetTests
{
    private static async Task<object?> Sql(string connection, string text, params (string, object)[] values)
    {
        await using var db = new NpgsqlConnection(connection); await db.OpenAsync(); await using var command = new NpgsqlCommand(text, db);
        foreach (var (key, value) in values) command.Parameters.AddWithValue(key, value);
        return await command.ExecuteScalarAsync();
    }
    private static async Task<string> Database(string suffix)
    {
        var builder = new NpgsqlConnectionStringBuilder(Environment.GetEnvironmentVariable("PMS_TEST_CONNECTION_STRING"));
        if (builder.Database?.StartsWith("codex_pms_tests_", StringComparison.Ordinal) != true) throw new InvalidOperationException("Isolated test database required.");
        var name = builder.Database + "_" + suffix + "_" + Guid.NewGuid().ToString("N")[..8]; builder.Database = "postgres";
        await Sql(builder.ConnectionString, $"CREATE DATABASE \"{name}\""); builder.Database = name; return builder.ConnectionString;
    }
    private static async Task Drop(string connection)
    {
        var builder = new NpgsqlConnectionStringBuilder(connection); var name = builder.Database!;
        if (!name.StartsWith("codex_pms_tests_")) throw new InvalidOperationException("Unsafe cleanup target.");
        builder.Database = "postgres"; await Sql(builder.ConnectionString, $"DROP DATABASE \"{name}\" WITH (FORCE)");
    }
    private static async Task Seed(string edge, string shore, Guid a, Guid b)
    {
        await Sql(edge, """
            CREATE TABLE edge_provisioning_profile(is_active bool,node_id text,vessel_id uuid);
            CREATE TABLE sync_state(key text PRIMARY KEY,value text,updated_at timestamptz);
            CREATE TABLE sync_queue(id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,table_name text,event_id uuid,record_key text,
              action_type int,payload text,priority int,retry_count int,max_retries int,created_at timestamptz);
            CREATE TABLE equipment_assets(id uuid PRIMARY KEY,current_running_hours int,status text,maintenance_previous_status text,is_synced bool);
            CREATE TABLE maintenance_schedules(id int PRIMARY KEY,asset_id uuid REFERENCES equipment_assets);
            CREATE TABLE maintenance_tasks(id int PRIMARY KEY,schedule_id int REFERENCES maintenance_schedules);
            CREATE TABLE schedule_checklist_templates(id int PRIMARY KEY,schedule_id int REFERENCES maintenance_schedules);
            CREATE TABLE approval_documents(id int PRIMARY KEY,snapshot text);
            INSERT INTO edge_provisioning_profile VALUES(true,'RESET-A',@a);
            INSERT INTO equipment_assets VALUES('10000000-0000-0000-0000-000000000001',321,'MAINTENANCE','OPERATIONAL',true);
            INSERT INTO maintenance_schedules VALUES(1,'10000000-0000-0000-0000-000000000001');
            INSERT INTO maintenance_tasks VALUES(1,1); INSERT INTO schedule_checklist_templates VALUES(1,1);
            INSERT INTO sync_queue(table_name) VALUES('maintenance_task'),('maintenance_schedule'),('equipment_asset');
            INSERT INTO approval_documents VALUES(1,'signed evidence');
            """, ("a", a));
        await Sql(shore, """
            CREATE TABLE sync_node_trackers("NodeId" text,"VesselId" uuid,"IsRegistered" bool,"IsRevoked" bool);
            CREATE TABLE pms_sync_datasets("OriginNode" text PRIMARY KEY,"VesselId" uuid,"DatasetId" uuid,"StreamId" uuid,"IsActive" bool,"CreatedAt" timestamptz);
            CREATE TABLE equipment_assets(id int PRIMARY KEY,"VesselId" uuid,counter int);
            CREATE TABLE maintenance_schedules(id int PRIMARY KEY,"VesselId" uuid,asset int REFERENCES equipment_assets);
            CREATE TABLE maintenance_tasks(id int PRIMARY KEY,"VesselId" uuid,schedule int REFERENCES maintenance_schedules);
            CREATE TABLE schedule_checklist_templates(id int PRIMARY KEY,schedule int REFERENCES maintenance_schedules);
            INSERT INTO sync_node_trackers VALUES('RESET-A',@a,true,false);
            INSERT INTO equipment_assets VALUES(1,@a,321),(2,@b,123);
            INSERT INTO maintenance_schedules VALUES(1,@a,1),(2,@b,2);
            INSERT INTO maintenance_tasks VALUES(1,@a,1),(2,@b,2);
            INSERT INTO schedule_checklist_templates VALUES(1,1),(2,2);
            """, ("a", a), ("b", b));
    }
    [Fact]
    public async Task ResetIncludesShoreLegacyPhysicalNamesWithoutDeletingAnotherVessel()
    {
        var edge = await Database("edge_legacy"); var shore = await Database("shore_legacy");
        try
        {
            var a = Guid.NewGuid(); var b = Guid.NewGuid(); await Seed(edge, shore, a, b);
            await Sql(shore, """
                ALTER TABLE maintenance_tasks RENAME TO "MaintenanceTasks";
                CREATE TABLE task_deferral_request(id int PRIMARY KEY, task_id int REFERENCES "MaintenanceTasks");
                INSERT INTO task_deferral_request VALUES(1,1),(2,2);
                CREATE TABLE maintenance_histories(id int PRIMARY KEY, schedule_id int, task_id int);
                INSERT INTO maintenance_histories VALUES(1,1,1),(2,2,2);
                """);
            var reset = new DemoResetCoordinator(edge, shore);
            var preview = await reset.PreviewAsync("RESET-A", a);
            Assert.Equal(1, preview["shore:MaintenanceTasks"]); Assert.Equal(1, preview["shore:task_deferral_request"]);
            Assert.Equal(1, preview["shore:maintenance_histories"]);
            await Sql(shore, "UPDATE maintenance_histories SET task_id=2 WHERE id=1");
            await Assert.ThrowsAsync<InvalidOperationException>(() => reset.ApplyAsync("RESET-A", a, Guid.Parse("11111111-1111-4111-8111-111111111111")));
            await Sql(shore, "UPDATE maintenance_histories SET task_id=1 WHERE id=1");
            await reset.ApplyAsync("RESET-A", a, Guid.Parse("11111111-1111-4111-8111-111111111111"));
            Assert.Equal(1L, await Sql(shore, "SELECT count(*) FROM \"MaintenanceTasks\" WHERE \"VesselId\"=@b", ("b", b)));
            Assert.Equal(1L, await Sql(shore, "SELECT count(*) FROM task_deferral_request WHERE task_id=2"));
            Assert.Equal(0L, await Sql(shore, "SELECT count(*) FROM task_deferral_request WHERE task_id=1"));
            Assert.Equal(1L, await Sql(shore, "SELECT count(*) FROM maintenance_histories WHERE schedule_id=2"));
        }
        finally { await Drop(edge); await Drop(shore); }
    }

    [Theory]
    [InlineData(false)]
    [InlineData(true)]
    public async Task ScopedResetPreservesOtherDataAndResumesAfterExternalReferenceBlock(bool externalReference)
    {
        var edge = await Database("edge"); var shore = await Database("shore");
        try
        {
            var a = Guid.NewGuid(); var b = Guid.NewGuid(); var epoch = Guid.NewGuid(); await Seed(edge, shore, a, b);
            var reset = new DemoResetCoordinator(edge, shore); var preview = await reset.PreviewAsync("RESET-A", a);
            Assert.Equal(1, preview["edge:maintenance_tasks"]); Assert.Equal(1, preview["shore:maintenance_tasks"]);
            if (externalReference)
            {
                await Sql(edge, "CREATE TABLE inventory_references(id int PRIMARY KEY,task_id int REFERENCES maintenance_tasks ON DELETE CASCADE); INSERT INTO inventory_references VALUES(1,1)");
                await Assert.ThrowsAsync<InvalidOperationException>(() => reset.ApplyAsync("RESET-A", a, epoch));
                Assert.Equal(1L, await Sql(edge, "SELECT count(*) FROM maintenance_tasks"));
                Assert.Equal(2L, await Sql(shore, "SELECT count(*) FROM maintenance_tasks"));
                await Sql(edge, "DROP TABLE inventory_references");
            }
            await reset.ApplyAsync("RESET-A", a, epoch);
            Assert.Equal(0L, await Sql(edge, "SELECT count(*) FROM maintenance_tasks"));
            Assert.Equal(0L, await Sql(edge, "SELECT count(*) FROM schedule_checklist_templates"));
            Assert.Equal(1L, await Sql(shore, "SELECT count(*) FROM maintenance_tasks WHERE \"VesselId\"=@b", ("b", b)));
            Assert.Equal(1L, await Sql(shore, "SELECT count(*) FROM schedule_checklist_templates"));
            Assert.Equal(321, await Sql(edge, "SELECT current_running_hours FROM equipment_assets"));
            Assert.Equal("OPERATIONAL", await Sql(edge, "SELECT status FROM equipment_assets"));
            Assert.Equal(false, await Sql(edge, "SELECT is_synced FROM equipment_assets"));
            Assert.Equal(2L, await Sql(edge, "SELECT count(*) FROM sync_queue WHERE table_name='equipment_asset'"));
            Assert.Equal(2L, await Sql(shore, "SELECT count(*) FROM equipment_assets"));
            Assert.Equal(1L, await Sql(edge, "SELECT count(*) FROM approval_documents"));
            Assert.Equal("equipment_asset", await Sql(edge, "SELECT table_name FROM sync_queue"));
            Assert.Equal("ACTIVE", await Sql(edge, "SELECT value FROM sync_state WHERE key='pms-cutover-state'"));
            Assert.Equal(true, await Sql(shore, "SELECT \"IsActive\" FROM pms_sync_datasets"));
            await Sql(edge, "INSERT INTO maintenance_schedules VALUES(2,'10000000-0000-0000-0000-000000000001')"); await reset.ApplyAsync("RESET-A", a, epoch);
            Assert.Equal(1L, await Sql(edge, "SELECT count(*) FROM maintenance_schedules"));
            await Assert.ThrowsAsync<InvalidOperationException>(() => reset.ApplyAsync("RESET-A", a, Guid.NewGuid()));
        }
        finally { await Drop(edge); await Drop(shore); }
    }
}
